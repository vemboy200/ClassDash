async function detectErrorPage(page) {
  return await page.evaluate((headings) => {
    if (document.querySelectorAll('li[data-stream-item-id]').length > 0) return null;
    const h1 = [...document.querySelectorAll('h1')].map(e => (e.textContent || '').trim());
    return h1.find(t => headings.includes(t)) || null;
  }, ERROR_HEADINGS);
}

// ── Сбор заданий из одного класса ────────────────────────────

async function scrapeClass(page, cls, срок = TIMEOUT) {
  const url = `https://classroom.google.com/u/${U}/w/${cls.id}/t/all`;
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: TIMEOUT });

  // Куки протухают. Если Google увёл нас на вход — молча собрать
  // пустоту хуже, чем громко упасть.
  if (page.url().includes('accounts.google.com')) {
    throw new Error('куки протухли, нужен повторный вход: node 05-playwright-черновик.js --login');
  }

  // ВОТ РАДИ ЭТОГО ВСЁ И ЗАТЕВАЛОСЬ.
  // Не sleep вслепую, а ожидание конкретного элемента.
  // Если за минуту не появился — значит правда пусто, а не недогруз.
  //
  // Важно: ждать надо именно li[data-stream-item-id]. По [role="listitem"]
  // ждать нельзя — под него подходят пункты меню Stream/Classwork/People,
  // они появляются мгновенно, и ожидание заканчивается до того,
  // как приедут сами задания.
  try {
    await page.waitForSelector('li[data-stream-item-id]', { timeout: срок });

    // МАЛО ДОЖДАТЬСЯ ПЕРВОГО ЗАДАНИЯ. Classroom дорисовывает список
    // постепенно, и если прочитать его сразу, получишь кусок.
    //
    // Поймали 11 августа: после перехода на параллельное чтение три
    // вкладки стали грузиться одновременно, каждая медленнее, и сбор
    // выхватил 21 задание вместо 38. Хуже того — недостающие 17 на
    // следующем запуске вернулись бы и выглядели как новые.
    //
    // Поэтому ждём, пока количество заданий перестанет расти.
    let было = -1, стабильно = 0;
    for (let i = 0; i < 40; i++) {
      const стало = await page.evaluate(
        () => document.querySelectorAll('li[data-stream-item-id]').length);
      if (стало === было) {
        // Три замера подряд без изменений — считаем, что дорисовалось.
        if (++стабильно >= 3) break;
      } else {
        стабильно = 0;
      }
      было = стало;
      await page.waitForTimeout(500);
    }
  } catch {
    // Заданий нет — но почему? Вариантов два: класс правда пустой
    // или Classroom показал страницу ошибки. Молча вернуть «пусто»
    // во втором случае — как раз то, чего мы боимся: скрипт будет
    // бодро молчать, пока копятся дедлайны.
    const ошибка = await detectErrorPage(page);
    if (ошибка) {
      throw new Error(`Classroom ответил «${ошибка}» — проверь id класса и аккаунт`);
    }
    console.warn(`  ${cls.name}: за ${срок / 1000}с заданий не появилось`);
    return [];
  }

  return await page.evaluate(({ className, classId, authuser }) => {
    // Атрибут data-stream-item-id висит на нескольких вложенных узлах
    // одного задания, поэтому берём только li — это внешняя обёртка.
    const items = [...document.querySelectorAll('li[data-stream-item-id]')];

    return items.map(el => {
      const lines = (el.innerText || '')
        .split('\n')
        .map(s => s.trim())
        .filter(Boolean)
        // выкидываем служебное: имена иконок и подпись кнопки «⋮»
        // live_help добавлен 24 августа: это имя иконки, и без него
        // оно уехало в НАЗВАНИЕ задания — в «Просрочено» висела карточка
        // с заголовком «live_help».
        //
        // Добавлять сюда можно только то, что видели своими глазами.
        // Вписать заодно «quiz» или «class» — ловушка: пропадёт задание,
        // которое учитель правда так назвал.
        .filter(l => !['more_vert', 'More options', 'assignment', 'book',
                       'assignment_ind', 'help_outline', 'live_help'].includes(l));

      // Первая строка — тип (Assignment / Material / Quiz assignment),
      // дальше название, дальше срок.
      const type = lines[0] || '';
      const dated = l => l.startsWith('Due') || l.startsWith('Posted');
      const title = lines.slice(1).find(l => !dated(l)) || '';

      // Ссылку приходится СОБИРАТЬ, а не искать: тега <a> внутри
      // задания нет, Classroom раскрывает его на месте через JS.
      //
      // Проверено вручную: и classId, и id задания — это base64
      // от обычного числа, а рабочий адрес выглядит так:
      //   classroom.google.com/c/<classId>/a/<id в base64>/details
      // Для материалов тот же адрес сам перекидывает на /m/.
      //
      // Аккаунт указывается почтой (?authuser=), а не номером /u/N/:
      // номер у каждого браузера свой и меняется при добавлении
      // аккаунтов, почта — нет.
      //
      // Вложения (гуглдоки и прочее) лежат внутри задания, в списке
      // их не видно — за ними пришлось бы открывать каждое задание
      // отдельно, по 25-40 секунд на штуку. Отложено.
      const id = el.getAttribute('data-stream-item-id');
      const link = id
        ? `https://classroom.google.com/c/${classId}/a/${btoa(id)}/details` +
          `?authuser=${encodeURIComponent(authuser)}`
        : null;

      return {
        class: className,
        id,
        type,
        title,
        link,
        due: lines.find(l => l.startsWith('Due')) || null,
        posted: lines.find(l => l.startsWith('Posted')) || null,
      };
    }).filter(x => x.title);
  }, { className: cls.name, classId: cls.id, authuser: AUTHUSER });
}

