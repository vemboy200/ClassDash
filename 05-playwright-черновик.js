// ── Режим логина ─────────────────────────────────────────────

async function login() {
  const ctx = await chromium.launchPersistentContext(PROFILE_DIR, {
    channel: 'chrome',        // настоящий Chrome, а не урезанный chromium:
                              // иначе Google режет вход как «небезопасный браузер»
    headless: false,          // окно должно быть видимым — входить будет человек
    viewport: { width: 1280, height: 900 },
  });
  const page = await ctx.newPage();
  await page.goto('https://classroom.google.com/');

  console.log('\nВойди в школьный аккаунт в открывшемся окне.');
  console.log('Когда увидишь список классов — закрой окно.\n');

  // Ждём, пока человек закончит. Просто держим процесс живым.
  await new Promise(resolve => ctx.on('close', resolve));
  console.log('Профиль сохранён в', PROFILE_DIR);
}

