// ── Метки времени в логе ─────────────────────────────────────
//
// Лог пишется launchd в запуски.log и растёт на несколько тысяч строк
// в неделю. Двадцать тысяч строк БЕЗ ЕДИНОЙ МЕТКИ ВРЕМЕНИ — и когда
// в августе разбирали, почему сторож оборвал 72 прохода, время каждого
// приходилось вычислять по соседним записям. Дорого и ненадёжно.
//
// Поэтому каждая строка получает время. Первая строка запуска — с датой:
// лог живёт неделями, и без даты «14:22» ничего не значит.
//
// Многострочный вывод (сводка, списки заданий) помечается только по первой
// строке: если метить каждую, читаемые куски превращаются в столбик цифр.
(function пометитьВремя() {
  const два = n => String(n).padStart(2, '0');
  const время = () => {
    const t = new Date();
    return `${два(t.getHours())}:${два(t.getMinutes())}:${два(t.getSeconds())}`;
  };

  for (const канал of ['log', 'warn', 'error']) {
    const прежний = console[канал].bind(console);
    console[канал] = (...части) => {
      if (typeof части[0] === 'string') {
        // Пустая строка остаётся пустой: она разделитель, а не сообщение.
        if (части[0] === '') прежний(...части);
        else прежний(`${время()} ${части[0]}`, ...части.slice(1));
      } else {
        прежний(`${время()}`, ...части);
      }
    };
  }

  // Шапку печатаем, только если файл ЗАПУСТИЛИ, а не подключили как
  // библиотеку: иначе проверки на стенде засоряются чужими заголовками.
  if (require.main !== module) return;

  const t = new Date();
  console.log(`\n${'─'.repeat(60)}`);
  console.log(`ЗАПУСК ${t.toLocaleString('ru-RU', {
    day: '2-digit', month: '2-digit', year: 'numeric',
    hour: '2-digit', minute: '2-digit', second: '2-digit',
  })}`);
})();

