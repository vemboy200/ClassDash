/**
 * Сравнивает собранное с прошлым запуском и возвращает новое.
 *
 * ВТОРОЙ АРГУМЕНТ ВАЖНЕЕ, ЧЕМ КАЖЕТСЯ. Это список классов, которые
 * в этот раз НЕ ПРОЧИТАЛИСЬ (таймаут, сеть, что угодно).
 *
 * Без него был баг, поймали на живых данных 11 августа:
 *   1. GUSD Internships не открылся за минуту, скрипт его пропустил;
 *   2. в память записался урезанный список — без 32 заданий этого класса;
 *   3. на следующем запуске класс открылся нормально;
 *   4. скрипт сравнил с памятью и решил, что все 32 задания новые;
 *   5. всплывашка «новых: 32» на пустом месте.
 *
 * Одна сетевая заминка — и флуд. Поэтому: задания классов, которые
 * не прочитались, берём из прошлой памяти и переносим как есть.
 * Они не считаются новыми и не пропадают.
 */
function diffWithPrevious(current, сломались = []) {
  let previous = [];
  if (fs.existsSync(STATE_FILE)) {
    try { previous = JSON.parse(fs.readFileSync(STATE_FILE, 'utf8')); } catch {}
  }

  // Ключ — внутренний id задания из Classroom: он не меняется,
  // даже если учитель переименует задание.
  const key = x => x.id || `${x.class}::${x.title}`;

  // Переносим прошлые записи тех классов, которые сейчас не открылись.
  // ИСТОЧНИК МОЖЕТ НАЗЫВАТЬСЯ НЕ ТАК, КАК КЛАСС ВНУТРИ НЕГО.
  //
  // У Classroom имя источника и имя класса — одно и то же слово, поэтому
  // сравнения по x.class хватало. У Canvas и Edpuzzle в «сломались»
  // попадает имя площадки («Canvas»), а в поле class у заданий стоит имя
  // курса («English 9 1 - Kirakosyan - Per 6»). Совпадений ноль, переносить
  // нечего — и задания молча выпадали из памяти, чтобы вернуться «новыми»
  // следующим проходом. Та же беда, что с «новых: 32», только для двух
  // других площадок и невидимая, пока в них ноль заданий.
  //
  // Поэтому смотрим оба поля. У заданий Classroom поля «платформа» нет
  // вовсе, там второе условие просто не срабатывает.
  const неЧитался = x =>
    сломались.includes(x.class) || сломались.includes(x.платформа);

  // ЗАДАНИЕ, ПРОПАВШЕЕ ИЗ ПРОЧИТАННОГО КЛАССА, ВЫБРАСЫВАЕМ НЕ СРАЗУ.
  //
  // Защита выше ловит случай «класс не открылся». Но есть третий случай,
  // который выглядит как успех: класс открылся и честно отдал НЕПОЛНЫЙ
  // список — Classroom не дорисовал. Для скрипта это неотличимо
  // от «учитель удалил задания».
  //
  // Поймано на живых данных 24 августа, с точностью до штуки:
  //   проход N:    GUSD отдал 11 заданий вместо 30 → в память легло 11
  //   проход N+1:  GUSD отдал 30 → 19 выглядят новыми → всплывашка «19 новых»
  // 30 − 11 = 19. Недоборы не единичны: у AP World Hist класс отдавал
  // 1 задание вместо 3 в шестнадцати проходах из ста двадцати.
  //
  // Правило «три промаха подряд»: пропало один раз — скорее всего недобор,
  // держим. Пропало трижды подряд (полчаса) — значит правда удалили.
  // Недорисовка случайна и подряд не повторяется, а удаление необратимо,
  // поэтому три попытки различают их надёжно.
  //
  // Побочная выгода для Canvas и Edpuzzle: они отдают только несданное,
  // и сданное задание исчезает из списка. Теперь оно уходит не рывком,
  // а спустя полчаса — заодно видно, что сдача засчиталась.
  const ПОРОГ_ПРОПАЖИ = 3;

  const сейчасЕсть = new Set(current.map(key));
  const перенесённые = [];
  const недобор = [];
  const удалённые = [];

  for (const x of previous) {
    if (сейчасЕсть.has(key(x))) continue;   // пришло в этот раз — вопросов нет

    if (неЧитался(x)) { перенесённые.push(x); continue; }

    const пропал = (x.пропал || 0) + 1;
    if (пропал < ПОРОГ_ПРОПАЖИ) {
      перенесённые.push({ ...x, пропал });
      недобор.push(x);
    } else {
      // ИСЧЕЗНУВШЕЕ ПОМЕЧАЕМ, А НЕ ВЫБРАСЫВАЕМ.
      //
      // Сначала оно просто удалялось из памяти, и со стороны это выглядело
      // как «задание пропало само». Для одного человека, который помнит,
      // что делал, ещё терпимо. Для чужих людей — прямая потеря доверия:
      // список молча стал короче, и непонятно, была там работа или нет.
      //
      // Теперь запись остаётся навсегда, с отметкой и датой. Она не горит,
      // не считается новой и не попадает в счётчики — просто лежит
      // и подтверждает: это не потерялось, это учитель убрал.
      //
      // Если задание вернут, отметка снимется сама: пришедшее берётся
      // из current, а там ни «пропал», ни «удалено» нет вовсе.
      удалённые.push(x);
      перенесённые.push({
        ...x,
        пропал,
        удалено: true,
        когдаУдалено: x.когдаУдалено || new Date().toISOString(),
      });
    }
  }

  if (сломались.length) {
    console.log(`Не прочитались: ${сломались.join(', ')} — ` +
                `беру ${перенесённые.length - недобор.length} заданий из прошлой памяти`);
  }
  if (недобор.length) {
    console.log(`Недобор: ${недобор.length} заданий не пришло из прочитанных ` +
                `классов — держу их в памяти (${ПОРОГ_ПРОПАЖИ} промаха подряд = удалено)`);
  }
  if (удалённые.length) {
    console.log(`Пропали из Classroom (${ПОРОГ_ПРОПАЖИ} промаха подряд), ` +
                `помечаю удалёнными: ` + удалённые.map(x => x.title).join(', '));
  }

  // Счётчик промахов сбрасывается сам: пришедшее задание берётся
  // из current, а там поля «пропал» нет вовсе.
  const итог = [...current, ...перенесённые];
  const seen = new Set(previous.map(key));
  const fresh = итог.filter(x => !seen.has(key(x)));

  // ПАМЯТЬ ЗДЕСЬ НАМЕРЕННО НЕ ПИШЕТСЯ, см. запомнитьСбор.
  return { fresh, итог };
}

/**
 * Записывает память о собранных заданиях.
 *
 * ВЫНЕСЕНО ОТДЕЛЬНО И ЗОВЁТСЯ В САМОМ КОНЦЕ — это не наведение красоты.
 *
 * Раньше память сохранялась прямо внутри diffWithPrevious, то есть за сотню
 * строк до всплывашки. Упади что-нибудь между ними — и задание уже помечено
 * «видели», а сказать о нём не успели. Второго раза не будет: на следующем
 * проходе оно уже не новое.
 *
 * Так и случилось бы 1 сентября с багом `x.due.replace`: скрипт падал на
 * первом задании со сроком из Canvas — уже после записи памяти.
 *
 * Теперь при падении память остаётся вчерашней, и следующий проход покажет
 * то же самое ещё раз. Размен сознательный: лишняя всплывашка — это шум,
 * пропущенная — это пропущенный дедлайн.
 */
function запомнитьСбор(итог) {
  fs.writeFileSync(STATE_FILE, JSON.stringify(итог, null, 2));
}

/**
 * Перерисовывает `сводка.html` из памяти, ничего не собирая.
 *
 * Всё берётся из файлов: задания, объявления и пометки «новое». Сбор
 * не нужен — данные уже лежат, меняется только то, как их напечатать.
 */
function перерисовать() {
  const now = new Date();
  const прочесть = (файл, поумолчанию) => {
    try { return JSON.parse(fs.readFileSync(файл, 'utf8')); } catch { return поумолчанию; }
  };

  const задания = прочесть(STATE_FILE, []);
  const объявления = прочесть(STREAM_FILE, []);
  const свежее = прочесть(FRESH_FILE, { задания: [], объявления: [] });

  const { burning, later, undated, отложенные, просрочено, пропавшие } =
    разложить(задания, now, прочитатьТихие(), прочитатьСкрытые());

  записатьСтраницу({
    burning, later, undated, отложенные, просрочено, пропавшие,
    freshIds: new Set(свежее.задания || []),
    сломались: [], now,
    объявления,
    новыеОбъявления: new Set(свежее.объявления || []),
  }, PAGE_FILE);

  console.log(`Страница перерисована (язык: ${require('./18-язык.js').текущийЯзык()})`);
}

