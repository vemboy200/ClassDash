/**
 * Читает список классов со страницы classroom.google.com/u/N/h.
 *
 * НАЗВАНИЕ БЕРЁМ ИЗ aria-label, А НЕ ИЗ ТЕКСТА ССЫЛКИ.
 * aria-label — служебная подпись для программ чтения экрана, и в ней
 * название лежит чистым: «AP World Summer Prep. - 2026». А видимый
 * текст приезжает с мусором — «A\nAP World Summer Prep. - 2026»,
 * где первая буква это кружок-иконка класса.
 *
 * У каждой карточки две ссылки на один класс: сама карточка и «Open
 * your work for …». Вторую отбрасываем, иначе название класса стало бы
 * английской фразой про открытие работ.
 */
async function получитьКлассы(page) {
  await page.goto(`https://classroom.google.com/u/${U}/h`,
                  { waitUntil: 'domcontentloaded', timeout: TIMEOUT });

  if (page.url().includes('accounts.google.com')) {
    throw new Error('куки протухли, нужен повторный вход: node 05-playwright-черновик.js --login');
  }

  await page.waitForSelector('a[href*="/c/"]', { timeout: 30000 });

  // Та же грабля, что со списком заданий: Classroom дорисовывает
  // карточки постепенно, и первая появившаяся ссылка не значит, что
  // приехали все. Ждём, пока их количество не перестанет расти.
  let было = -1, стабильно = 0;
  for (let i = 0; i < 30; i++) {
    const стало = await page.evaluate(
      () => document.querySelectorAll('a[href*="/c/"]').length);
    if (стало === было) { if (++стабильно >= 3) break; } else стабильно = 0;
    было = стало;
    await page.waitForTimeout(500);
  }

  return await page.evaluate(() => {
    const метки = new Map();   // id -> название из aria-label
    const тексты = new Map();  // id -> запасное название из текста ссылки

    for (const a of document.querySelectorAll('a[href*="/c/"]')) {
      const m = (a.getAttribute('href') || '').match(/\/c\/([A-Za-z0-9_-]+)/);
      if (!m) continue;
      const id = m[1];

      const метка = (a.getAttribute('aria-label') || '').trim();
      if (метка && !/^Open your work for/i.test(метка) && !метки.has(id)) {
        метки.set(id, метка.replace(/\s+/g, ' '));
      }

      // Запасной вариант: самая длинная строка видимого текста.
      // Короткие — это буква на иконке и подписи кнопок.
      if (!тексты.has(id)) {
        const строки = (a.innerText || '').split('\n')
          .map(s => s.trim()).filter(s => s.length > 2);
        if (строки.length) {
          тексты.set(id, строки.sort((a, b) => b.length - a.length)[0]);
        }
      }
    }

    const все = new Set([...метки.keys(), ...тексты.keys()]);
    return [...все].map(id => ({ id, name: метки.get(id) || тексты.get(id) || id }));
  });
}

/** Последний удачно прочитанный список классов. */
function классыИзПамяти() {
  if (fs.existsSync(CLASSES_FILE)) {
    try {
      const список = JSON.parse(fs.readFileSync(CLASSES_FILE, 'utf8'));
      if (Array.isArray(список) && список.length) return список;
    } catch {}
  }
  return CLASSES_ЗАПАСНЫЕ;
}

/**
 * Список классов на этот проход.
 *
 * ПУСТОЙ ОТВЕТ НЕ ЗНАЧИТ «КЛАССОВ НЕТ». Страница могла не догрузиться,
 * сеть моргнуть, куки протухнуть. Если поверить пустоте, скрипт замолчит
 * на весь день, считая, что учиться негде, — ровно тот провал, ради
 * которого всё это писалось. Поэтому при любой неудаче берём последний
 * список, который читался успешно.
 */
async function списокКлассов(page) {
  let найденные = [];
  try {
    найденные = await получитьКлассы(page);
  } catch (e) {
    if (/куки протухли/.test(e.message)) КУКИ_ПРОТУХЛИ = true;
    console.warn(`  список классов не прочитался (${e.message}) — беру прошлый`);
  }

  if (!найденные.length) {
    const прошлые = классыИзПамяти();
    console.log(`Классов: ${прошлые.length} (из памяти, страница списка не ответила)`);
    return прошлые.filter(к => !ИСКЛЮЧЕНИЯ.includes(к.name));
  }

  // Запоминаем ДО вычитания исключений: исключение — это решение
  // «не читать», а не «такого класса не существует». Уберём его
  // из списка потом — так класс вернётся, стоит убрать строку.
  fs.writeFileSync(CLASSES_FILE, JSON.stringify(найденные, null, 2));

  const отобранные = найденные.filter(к => !ИСКЛЮЧЕНИЯ.includes(к.name));
  console.log(`Классов: ${отобранные.length}` +
    (ИСКЛЮЧЕНИЯ.length ? ` (пропускаю по списку исключений: ${ИСКЛЮЧЕНИЯ.join(', ')})` : ''));
  return отобранные;
}

