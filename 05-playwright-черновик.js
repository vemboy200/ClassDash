if (require.main !== module) return;

(async () => {
  // ПЕРЕРИСОВАТЬ СТРАНИЦУ БЕЗ СБОРА.
  //
  // Нужен для смены языка. Язык — настройка интерфейса, а не поиска, и ждать
  // ради неё десять минут до следующего сбора неправильно (замечание пользователя,
  // и оно верное). Браузер здесь не запускается вовсе: берём то, что уже
  // лежит в памяти, и печатаем страницу заново. Полсекунды вместо минуты.
  if (process.argv.includes('--перерисовать')) {
    перерисовать();
    return;
  }

  if (process.argv.includes('--login')) {
    await login();
    return;
  }

  if (!захватитьЗамок()) {
    console.log('Сбор уже идёт, этот запуск пропускаю.');
    return;
  }
  // Снимаем замок при любом исходе: и при падении, и при Ctrl+C.
  process.on('exit', снятьЗамок);
  process.on('SIGINT', () => process.exit(1));
  process.on('SIGTERM', () => process.exit(1));

  // СТОРОЖ: проход не должен уметь длиться вечно (см. ПРЕДЕЛ_ПРОХОДА).
  //
  // unref() означает «этот таймер не держит программу живой». Без него
  // каждый нормальный проход досиживал бы до конца пяти минут вместо
  // того, чтобы завершиться за семнадцать секунд. Сработать таймеру это
  // не мешает: пока программа жива, он живёт вместе с ней.
  const сторож = setTimeout(() => {
    const предел = ПРЕДЕЛ_ПРОХОДА >= 60000
      ? `${Math.round(ПРЕДЕЛ_ПРОХОДА / 60000)} мин`
      : `${Math.round(ПРЕДЕЛ_ПРОХОДА / 1000)} с`;
    console.error(`\nПроход идёт дольше ${предел} — обрываю. ` +
                  'Замок снимется, следующий запуск пойдёт по расписанию.');

    // Добиваем браузер. Оборванный node не закрывает Chrome за собой,
    // а тот держит папку профиля — и следующий запуск упал бы уже
    // с «Failed to create SingletonLock: File exists».
    // Ищем именно наш процесс: по пути к профилю, а не по имени Chrome,
    // чтобы не задеть обычный браузер пользователя.
    try {
      require('child_process').execFileSync('pkill', ['-f', `user-data-dir=${PROFILE_DIR}`]);
    } catch { /* нечего убивать — pkill ругается, и это нормально */ }

    process.exit(1);
  }, ПРЕДЕЛ_ПРОХОДА);
  сторож.unref();

  const now = new Date();

  // Память с прошлого запуска нужна ещё ДО сбора: пока классы читаются,
  // страница показывает по ним старые данные, а не пустоту.
  let память = [];
  if (fs.existsSync(STATE_FILE)) {
    try { память = JSON.parse(fs.readFileSync(STATE_FILE, 'utf8')); } catch {}
  }

  // Список перечитывается каждый запуск: пользователь мог нажать «не срочно»
  // минуту назад, пока шёл предыдущий сбор.
  const тихие = прочитатьТихие();
  const скрытые = прочитатьСкрытые();

  // Классы, в которых по нашей памяти когда-либо были задания.
  // Остальным даём укороченное ожидание — см. TIMEOUT_ПУСТОЙ.
  const непустые = new Set(память.map(x => x.class));

  // Читать ли Edpuzzle. Ему нужно видимое окно, а оно перебрасывает
  // рабочий стол — поэтому не каждый раз, а только когда это уместно:
  //
  //   - в часы полной сводки (8:00 и 18:00): пользователь обычно за компом;
  //   - при ручном запуске (--всё): он сам нажал, значит готов.
  //
  // В остальные 46 запусков в день читаются только Classroom и Canvas,
  // и никакого окна не появляется вообще.
  // ── Пора ли показывать полную сводку ──
  //
  // Считается ЗДЕСЬ, до сбора, а не после — потому что от этого зависит,
  // открывать ли видимое окно ради Edpuzzle.
  //
  // РАНЬШЕ БЫЛО `DIGEST_HOURS.includes(now.getHours())`, и это оказалось
  // дорогой ошибкой: в расписании launchd ШЕСТЬ моментов внутри восьмого
  // часа (8:00, 8:10, … 8:50), и час у всех шести одинаковый. Значит окно
  // открывалось шесть раз подряд, и каждый раз macOS выдёргивала пользователя
  // на рабочий стол Chrome. В досье записано «два переброса в день»,
  // а по логу их было семь: шесть утром плюс один в 18:00.
  //
  // Журнал `журнал-уведомлений.json` уже помнит, в какой день и час сводку
  // показывали. На него и опираемся: сводка (а с ней и окно) положена
  // один раз на каждый час из списка.
  const сегодня = new Date(now.getTime() - now.getTimezoneOffset() * 60000)
    .toISOString().slice(0, 10);
  const час = now.getHours();

  let журнал = { сводки: {} };
  if (fs.existsSync(NOTIFY_LOG)) {
    try {
      журнал = JSON.parse(fs.readFileSync(NOTIFY_LOG, 'utf8'));
      журнал.сводки = журнал.сводки || {};
    } catch {}
  }

  const времяСводки = DIGEST_HOURS.includes(час) && журнал.сводки[час] !== сегодня;

  const вручную = process.argv.includes('--всё');
  const сEdpuzzle = вручную || времяСводки;
  console.log(сEdpuzzle
    ? `Полная проверка${вручную ? ' (запущена вручную)' : ''}: с Edpuzzle, будет видимое окно`
    : 'Быстрая проверка: Classroom и Canvas, без окна');

  задатьПочту(AUTHUSER);

  const { all: собрано, объявления, сломались } = await collect(({ items, прочитаны, сломались, читаем }) => {
    // К уже прочитанному добавляем из памяти то, до чего ещё не дошли.
    // Та же поправка, что в diffWithPrevious: имя источника и имя класса
    // внутри него — разные вещи. Без проверки платформы задания Canvas
    // считались бы «ещё не прочитанными» даже после того, как Canvas
    // прочитан, и попадали бы на страницу дважды: свежие плюс те же
    // самые из памяти.
    const изПамяти = память.filter(
      x => !прочитаны.includes(x.class) && !прочитаны.includes(x.платформа));
    const вместе = [...items, ...изПамяти];
    const { burning, later, undated, отложенные, просрочено, пропавшие } =
      разложить(вместе, now, тихие, скрытые);

    // Значков «новое» по ходу не ставим: что именно новое, станет
    // понятно только когда прочитаны все классы.
    записатьСтраницу(
      { burning, later, undated, отложенные, просрочено, пропавшие,
        freshIds: new Set(), сломались, читаем, now },
      PAGE_FILE,
    );
  }, непустые, сEdpuzzle);

  // ИСТОЧНИК, КОТОРЫЙ НЕ ЧИТАЛИ, ВЕДЁТ СЕБЯ КАК СЛОМАВШИЙСЯ: его задания
  // берутся из памяти и не считаются новыми.
  //
  // Касается и Edpuzzle в быстром режиме, и Canvas, выключенного пустым
  // адресом. Без этого была бы та же беда, что с «новых: 32», только
  // с другой стороны: задания вылетели бы из памяти, а в следующий полный
  // проход вернулись бы как новые.
  const непрочитанные = [
    ...(сEdpuzzle ? [] : ['Edpuzzle']),
    ...(С_CANVAS ? [] : ['Canvas']),
  ];

  const { fresh, итог: all } = diffWithPrevious(собрано, [...сломались, ...непрочитанные]);
  const freshIds = new Set(fresh.map(x => x.id));

  const { burning, later, undated, отложенные, просрочено, пропавшие, past } =
    разложить(all, now, тихие, скрытые);

  // ── Объявления ──
  // Живут отдельно от заданий: у них нет сроков, они не «горят»,
  // но важна свежесть. Поэтому и память у них своя.
  let памятьСообщений = [];
  if (fs.existsSync(STREAM_FILE)) {
    try { памятьСообщений = JSON.parse(fs.readFileSync(STREAM_FILE, 'utf8')); } catch {}
  }
  const виделиСообщения = new Set(памятьСообщений.map(x => x.id));
  const новыеОбъявления = объявления.filter(x => !виделиСообщения.has(x.id));

  // ПАМЯТЬ ОБЪЯВЛЕНИЙ ДОПОЛНЯЕТСЯ, А НЕ ПЕРЕЗАПИСЫВАЕТСЯ.
  //
  // У заданий мы переносим из памяти только те классы, которые не
  // прочитались. Для объявлений этого мало: лента может отдать не все
  // посты, даже когда класс формально прочитался. Поймали на живых
  // данных — во время сна мака лента отдала 17 постов вместо 19,
  // два вылетели из памяти и на следующем проходе вернулись «новыми».
  //
  // Объявления, в отличие от заданий, не исчезают: учитель их почти
  // никогда не удаляет. Поэтому просто складываем старое с новым
  // по id — свежая версия побеждает, потерянное остаётся.
  const склад = new Map(памятьСообщений.map(x => [x.id, x]));
  for (const п of объявления) склад.set(п.id, п);
  const всеОбъявления = [...склад.values()];

  // СОРТИРУЕМ ПО ДАТЕ, свежие сверху.
  //
  // До этого порядок был бессмысленный: объявления шли по классам,
  // а внутри класса по свежести — то есть майский пост одного класса
  // мог стоять выше августовского из другого.
  //
  // Даты у постов текстовые («Aug 8», «Jun 4»), года нет. Разбираем
  // тем же parseDue, что и сроки заданий: он умеет выбирать ближайший
  // год в обе стороны, поэтому январские посты не улетают в будущее.
  for (const п of всеОбъявления) {
    const { at } = parseDue(п.дата, now);

    // ВАЖНАЯ ПОПРАВКА к общему правилу разбора дат.
    //
    // parseDue выбирает ближайший год В ОБЕ СТОРОНЫ — для дедлайнов это
    // правильно. Но объявление не может быть из будущего: его уже
    // написали. Без поправки «Jan 13» толковался как январь следующего
    // года (до него ближе, чем назад) и январский пост оказывался
    // свежее августовского.
    if (at && at > now) at.setFullYear(at.getFullYear() - 1);

    п.когда = at ? at.getTime() : 0;
  }
  всеОбъявления.sort((a, b) => b.когда - a.когда);
  // Память объявлений тоже пишется в самом конце, вместе с заданиями.

  if (объявления.length) {
    console.log(`Объявлений в лентах: ${объявления.length}` +
                (новыеОбъявления.length ? `, новых: ${новыеОбъявления.length}` : ''));
  }

  const mark = x => (freshIds.has(x.id) ? ' ← новое' : '');
  const when = x => {
    if (x.note) return т(x.note);
    const days = днейДо(now, x.due_at);

    // У Classroom дата приходит текстом («Due Aug 25, 8:30 AM»),
    // у Canvas и Edpuzzle — машинным форматом, а текстового поля нет.
    // Раньше здесь стояло просто x.due.replace(...) и скрипт падал
    // целиком на первом же задании из Canvas со сроком. Нашлось
    // подставным заданием; в жизни это случилось бы первого сентября.
    const текст = x.due
      ? x.due.replace(/^Due\s+/, '')
      : x.due_at.toLocaleString(локаль(),
          { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });

    return `${текст} — через ${days} дн.`;
  };

  // Короткий срок для всплывашки: «сегодня», «завтра», «через 5 дн.»
  const когда = (due) => {
    const дней = днейДо(now, due);
    if (дней < 0) return т('просроченоНа', дней * -1);
    if (дней === 0) return т('сегодня');
    if (дней === 1) return т('завтра');
    return т('черезДней', дней);
  };

  // «1 новое», «2 новых», «5 новых» — иначе выглядит по-роботски.
  const склонение = (n, один, два, много) => {
    const п = n % 100;
    if (п >= 11 && п <= 14) return много;
    const е = n % 10;
    return е === 1 ? один : (е >= 2 && е <= 4 ? два : много);
  };

  console.log(`\n${'═'.repeat(60)}`);

  if (burning.length) {
    console.log('\nГОРИТ (неделя и ближе):');
    for (const x of burning) console.log(`  ${x.title}\n    ${x.class} · ${when(x)}${mark(x)}` +
                                 (x.link ? `\n    ${x.link}` : ''));
  }

  if (later.length) {
    console.log('\nВпереди:');
    for (const x of later) console.log(`  ${x.title}\n    ${x.class} · ${when(x)}${mark(x)}` +
                                 (x.link ? `\n    ${x.link}` : ''));
  }

  if (!burning.length && !later.length) {
    console.log('\nНичего с будущим сроком не найдено.');
  }

  const freshUndated = undated.filter(x => freshIds.has(x.id));
  if (freshUndated.length) {
    console.log('\nНовые материалы (показываю один раз):');
    for (const x of freshUndated) {
      console.log(`  ${x.title}\n    ${x.class}` + (x.link ? `\n    ${x.link}` : ''));
    }
  }

  console.log(`\n${'─'.repeat(60)}`);
  console.log(`Всего собрано: ${all.length} · новых: ${fresh.length} · ` +
              `без срока: ${undated.length} · в прошлом: ${past}`);

  // Страница пишется КАЖДЫЙ запуск, даже когда всплывашки не будет:
  // она должна быть свежей в любой момент, когда по ней кликнут.
  записатьСтраницу({
    burning, later, undated, отложенные, просрочено, пропавшие, freshIds, сломались, now,
    объявления: всеОбъявления,
    новыеОбъявления: new Set(новыеОбъявления.map(x => x.id)),
  }, PAGE_FILE);
  console.log(`Сводка: ${PAGE_FILE}`);

  // Кладём пометки рядом, чтобы перерисовка их не потеряла.
  try {
    fs.writeFileSync(FRESH_FILE, JSON.stringify({
      задания: [...freshIds],
      объявления: новыеОбъявления.map(x => x.id),
    }));
  } catch { /* не записалось — переживём, пропадут только значки */ }

  // ── Всплывашка ──
  //
  // Скрипт запускается каждые 10 минут, а задание горит неделями.
  // Если показывать горящее каждый раз — это 48 одинаковых всплывашек
  // в день, и через день их перестанут замечать. Поэтому два режима:
  //
  //   ОБЫЧНЫЙ ЗАПУСК — только то, чего раньше не было. Появилось
  //     новое задание — сказать сразу. Нет — молчать.
  //
  //   ПОЛНАЯ СВОДКА (часы из DIGEST_HOURS) — напомнить обо всём
  //     горящем, даже давно известном. Раз в день на каждый такой час,
  //     а не при каждом запуске внутри него.
  // сегодня, час, журнал и времяСводки посчитаны ДО сбора — от них
  // зависело, открывать ли окно ради Edpuzzle.

  // ── Открывшиеся курсы ──
  //
  // Когда учитель публикует курс посреди года, в нём сразу может лежать
  // два десятка заданий. Формально все они «новые» — их не было в памяти.
  // Но всплывашка «20 новых» бесполезна: это не двадцать новостей,
  // это одна новость — открылся курс.
  //
  // Поэтому задания только что появившегося курса в счётчик новых
  // не идут. Про сам курс сообщаем отдельной строкой, а задания
  // тихо ложатся в память и дальше живут обычной жизнью: если у них
  // есть сроки, они попадут в «Горит» своим чередом.
  const былиКурсы = new Set(память.map(x => x.class));
  const открылись = память.length
    ? [...new Set(all.map(x => x.class))].filter(к => !былиКурсы.has(к))
    : [];   // первый запуск вообще — там всё новое, и это нормально

  const новые = [...burning, ...later, ...undated]
    .filter(x => freshIds.has(x.id) && !открылись.includes(x.class));

  if (открылись.length) {
    for (const к of открылись) {
      const сколько = all.filter(x => x.class === к).length;
      console.log(`\nОткрылся курс: ${к} — заданий ${сколько}`);
    }
  }

  // Новое объявление — такой же повод сказать, как новое задание.
  // «Контрольная переносится» важнее половины списка заданий, и живёт
  // оно только в ленте. Первый запуск не в счёт: там новым выглядит всё.
  const свежиеОбъявления = памятьСообщений.length ? новыеОбъявления : [];

  // ПРО ПРОТУХШИЕ КУКИ ГОВОРИМ ОТДЕЛЬНО И ВПЕРЁД ВСЕГО ОСТАЛЬНОГО.
  //
  // Пока не войдёшь заново, система показывает вчерашнее и молчит. Лучше
  // одна назойливая всплывашка, чем неделя тишины с пропущенными дедлайнами.
  // Журнал тут не при чём: это не сводка, а поломка, и напоминать о ней
  // надо каждый раз, пока не починят.
  if (КУКИ_ПРОТУХЛИ) {
    console.log('\nКУКИ ПРОТУХЛИ — нужен повторный вход');
    notify(т('школа'), т('нуженВход'), т('нуженВходКак'));
    запомнитьСбор(all);
    fs.writeFileSync(STREAM_FILE, JSON.stringify(всеОбъявления, null, 2));
    return;
  }

  if (новые.length || открылись.length || свежиеОбъявления.length ||
      (времяСводки && burning.length)) {
    // ТЕЛО ВСПЛЫВАШКИ — ТОЛЬКО НАЗВАНИЕ И СРОК. Никаких «класс такой-то,
    // срок не проставлен, считаем до завтра» — прошлая версия занимала
    // три строки, и прочитать её на бегу было невозможно.
    // Подробности живут на странице, всплывашка только зовёт.
    //
    // Берём САМОЕ БЛИЖНЕЕ по сроку: списки уже отсортированы по дате.
    const поводы = новые.length ? новые : burning;
    const первое = поводы.length
      ? (поводы.find(x => x.due_at) || поводы[0])
      : null;

    // Открывшийся курс — сам по себе новость, и она важнее списка заданий.
    let тело;
    if (открылись.length) {
      тело = `${т('открылсяКурс')} ${открылись[0]}`;
    } else if (свежиеОбъявления.length && !новые.length) {
      // Новых заданий нет, но учитель что-то написал — показываем его.
      const п = свежиеОбъявления[0];
      тело = `${п.автор}: ${(п.текст || п.title || '').split('\n')[0]}`;
    } else if (первое) {
      const срок = первое.due_at
        ? (первое.note ? т('срокНеПроставлен') : когда(первое.due_at))
        : '';
      тело = срок ? `${первое.title} — ${срок}` : первое.title;
    } else {
      тело = т('откройСводку');
    }

    // Счётчики ушли в подзаголовок и написаны словами.
    // Прошлый вариант «Школа · новых: 32» пользователь прочитал как
    // «тридцать две всплывашки» — и был прав, так и читается.
    const части = [];
    if (открылись.length) {
      части.push(т('счётКурсов', открылись.length));
    }
    if (новые.length) части.push(т('счётНовых', новые.length));
    if (свежиеОбъявления.length) {
      части.push(т('счётСообщений', свежиеОбъявления.length));
    }
    if (времяСводки && burning.length) части.push(т('счётГорит', burning.length));

    notify(т('школа'), части.join(', '), тело);

    // Пишем в лог, что именно показали. Иначе по выводу невозможно
    // отличить «всплывашка ушла» от «скрипт молча решил не показывать»,
    // и остаётся только гадать, сработало или нет.
    console.log(`\nПоказал всплывашку: Школа · ${части.join(', ')}`);
    console.log(`                     ${тело}`);

  } else {
    console.log(времяСводки || !DIGEST_HOURS.length
      ? '\nВсплывашку не показываю: нового нет.'
      : `\nВсплывашку не показываю: нового нет, а полная сводка в ${DIGEST_HOURS.join(':00 и ')}:00.`);
  }

  // ЖУРНАЛ ОТМЕЧАЕТСЯ ВНЕ ЗАВИСИМОСТИ ОТ ТОГО, БЫЛА ЛИ ВСПЛЫВАШКА.
  //
  // Раньше отметка стояла внутри ветки «показал всплывашку». Пока час сводки
  // значил только «показать напоминание», это было неважно. Теперь от него
  // зависит и открытие окна Edpuzzle: если в 8:00 гореть было нечему
  // и отметки не осталось, в 8:10 всё повторилось бы заново — и окно
  // открывалось бы все шесть раз, ровно как до починки.
  //
  // Час сводки прошёл — значит прошёл. Всё новое, что появится позже,
  // и так получит свою всплывашку обычным порядком.
  if (времяСводки) {
    журнал.сводки[час] = сегодня;
    try {
      fs.writeFileSync(NOTIFY_LOG, JSON.stringify(журнал, null, 2));
    } catch (e) {
      console.warn('не записался журнал уведомлений:', e.message);
    }
  }

  // ── ПАМЯТЬ ПИШЕТСЯ ПОСЛЕДНЕЙ ──
  //
  // Только теперь, когда всплывашка показана и в лог всё выведено, можно
  // сказать «это мы видели». Всё, что могло упасть, уже отработало.
  // Подробности — в комментарии к запомнитьСбор.
  запомнитьСбор(all);
  fs.writeFileSync(STREAM_FILE, JSON.stringify(всеОбъявления, null, 2));
})();

