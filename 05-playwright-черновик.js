/**
 * Показывает всплывашку. Зовём ТОЛЬКО когда есть что сказать —
 * иначе смысл всей затеи теряется: уведомление, которое приходит
 * каждый час просто так, перестают замечать через два дня.
 *
 * Про «висит, пока не нажмёшь»: это не параметр команды, а настройка
 * системы. Системные настройки -> Уведомления -> найти приложение,
 * от чьего имени приходит всплывашка -> стиль «Оповещения» (Alerts)
 * вместо «Баннеры» (Banners). Баннер уезжает сам через несколько
 * секунд, оповещение остаётся на экране до нажатия.
 *
 * Поверх полноэкранной игры не покажется — на macOS полноэкранное
 * приложение занимает отдельный Space, и чужие окна туда не рисуются.
 * Но уведомление дождётся в Центре уведомлений, так что не потеряется.
 */
function notify(title, subtitle, message) {
  const { execFileSync } = require('child_process');

  // Основной путь: наше приложение Напоминалка.app.
  //
  // Запускаем ИСПОЛНЯЕМЫЙ ФАЙЛ внутри приложения напрямую.
  // Перебрали три способа, работает только этот:
  //
  //   osascript Напоминалка.app     — всплывашка приходит от
  //                                   «Редактора скриптов», не от нас
  //   open -a Напоминалка.app       — на этой машине открывает Finder
  //                                   вместо запуска приложения
  //   Contents/MacOS/applet         — работает: имя и значок наши
  //
  // Текст кладём в файл рядом, а не в аргументы: так до апплета он
  // доходит гарантированно, и кавычки в названиях заданий (а они там
  // есть, вроде «Neighborhood Ecology») ничего не ломают.
  const бинарник = path.join(NOTIFIER_APP, 'Contents', 'MacOS', 'applet');
  if (fs.existsSync(бинарник)) {
    try {
      // Три строки: заголовок, подзаголовок, текст.
      fs.writeFileSync(NOTIFY_FILE, `${title}\n${subtitle}\n${message}`);
      execFileSync(бинарник);
      return;
    } catch (e) {
      console.warn('Напоминалка.app не сработала:', e.message);
    }
  }

  // Запасной путь: если приложения нет (удалили, не собрали),
  // показать хоть как-нибудь. Здесь текст уже приходится вклеивать
  // в код, поэтому кавычки и слэши экранируем вручную.
  const esc = s => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  try {
    execFileSync('osascript', ['-e',
      `display notification "${esc(message)}" with title "${esc(title)}" sound name "Glass"`]);
  } catch (e) {
    console.warn('не удалось показать уведомление:', e.message);
  }
}

// ── Разбор дат ───────────────────────────────────────────────

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
                'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/**
 * Превращает "Due Aug 25, 8:30 AM" в настоящую дату.
 *
 * Две особенности Classroom:
 *
 * 1. Год он пишет, только если тот отличается от текущего.
 *    "Due Aug 25" — это ближайшее 25 августа.
 *
 * 2. Учителя, которым лень выбрать «no due date», ставят заглушку
 *    вида 2031 года. Это НЕ настоящий срок. Но и не «даты нет»:
 *    задание-то реальное, просто дату забыли. Договорились с пользователем
 *    считать такое срочным — до завтра, — чтобы оно не терялось.
 */
function parseDue(dueStr, now = new Date()) {
  if (!dueStr) return { at: null, placeholder: false };

  const s = dueStr.replace(/^Due\s+/, '');

  // БЛИЗКИЕ СРОКИ CLASSROOM ПИШЕТ СЛОВАМИ, А НЕ ДАТОЙ.
  //
  // «Due Today», «Due Tomorrow, 8:30 AM», а иногда и вовсе одно время —
  // «Due 8:00 AM», что значит сегодня. Регулярка ниже ждёт три буквы месяца
  // и следом цифру, поэтому ни одна из этих строк под неё не подходила:
  // «Today» — три буквы, но дальше «ay», а не число.
  //
  // Чем это было плохо: at выходил null, задание считалось «срок не проставлен
  // вообще», уезжало на «до завтра» и получало кнопку «не срочно». То есть
  // настоящий сегодняшний дедлайн сортировался НИЖЕ завтрашнего, никогда
  // не попадал в «Просрочено», а нажатие кнопки убирало его из виду совсем.
  //
  // Поймано независимой проверкой 24 августа на живой памяти: шесть из десяти
  // сроков не разбирались, и это были самые срочные задания.
  //
  // \b — «дальше не буква»: иначе под Tomorrow подошло бы «Tomorrowland».
  const словом = s.match(/^(Today|Tomorrow)\b(?:,\s*(\d{1,2}):(\d{2})\s*(AM|PM))?/i);
  const однимВременем = словом ? null : s.match(/^(\d{1,2}):(\d{2})\s*(AM|PM)/i);

  if (словом || однимВременем) {
    // «Только время» без даты значит сегодня.
    const назавтра = !!(словом && /^tomorrow$/i.test(словом[1]));
    const [чч, мм, дп] = словом
      ? [словом[2], словом[3], словом[4]]
      : [однимВременем[1], однимВременем[2], однимВременем[3]];

    // Времени нет — конец дня, ровно как у «Due Aug 26» без времени.
    let ч = чч ? parseInt(чч, 10) % 12 : 23;
    if (дп && /pm/i.test(дп)) ч += 12;
    const мин = мм ? parseInt(мм, 10) : 59;

    // Перевод через конец месяца Date считает сам: 31 августа + 1 = 1 сентября.
    const at = new Date(now.getFullYear(), now.getMonth(),
                        now.getDate() + (назавтра ? 1 : 0), ч, мин);
    return { at, placeholder: false };
  }

  const m = s.match(/^([A-Z][a-z]{2})\s+(\d{1,2})(?:,\s*(\d{4}))?(?:,\s*(\d{1,2}):(\d{2})\s*(AM|PM))?/);
  if (!m) return { at: null, placeholder: false };

  const [, mon, day, year, hh, mm, ampm] = m;
  const month = MONTHS.indexOf(mon);
  if (month < 0) return { at: null, placeholder: false };

  let hours = hh ? parseInt(hh, 10) % 12 : 23;
  if (ampm === 'PM') hours += 12;
  const minutes = mm ? parseInt(mm, 10) : 59;

  let at;
  if (year) {
    at = new Date(parseInt(year, 10), month, parseInt(day, 10), hours, minutes);
  } else {
    // Года нет — примеряем прошлый, текущий и следующий и берём тот,
    // что БЛИЖЕ ВСЕГО к сегодня, в любую сторону.
    //
    // Считать «раз года нет, значит год текущий» нельзя: 5 января
    // задание "Due Dec 20" — это просроченный декабрь позади,
    // а не декабрь через одиннадцать месяцев. Раньше скрипт
    // умел сдвигать только вперёд и в новогодние недели врал бы.
    const y = now.getFullYear();
    at = [y - 1, y, y + 1]
      .map(yy => new Date(yy, month, parseInt(day, 10), hours, minutes))
      .reduce((a, b) => (Math.abs(b - now) < Math.abs(a - now) ? b : a));
  }

  // Заглушка вместо «нет срока»: дальше чем на год вперёд.
  const placeholder = at - now > 365 * 864e5;
  return { at, placeholder };
}

/** Когда задание реально надо сделать (с учётом заглушек). */
function deadline(item, now = new Date()) {
  // Canvas отдаёт дату уже готовой, машинным форматом (due_iso).
  // Разбирать текст не нужно — но заглушка «2031 вместо no due date»
  // возможна и здесь, поэтому проверка на далёкое будущее общая.
  if (item.due_iso) {
    const at = new Date(item.due_iso);
    if (isNaN(at)) return null;
    if (at - now > 365 * 864e5) return new Date(now.getTime() + 864e5);
    return at;
  }

  const { at, placeholder } = parseDue(item.due, now);
  if (!at) return null;
  if (placeholder) return new Date(now.getTime() + 864e5); // «до завтра»
  return at;
}

// ── Раскладка по корзинам ────────────────────────────────────

/**
 * Раскладывает задания на «горит / впереди / без срока / в прошлом».
 *
 * Вынесено в отдельную функцию, потому что зовётся дважды: по ходу
 * сбора (чтобы перерисовывать страницу после каждого класса) и в конце.
 */
function разложить(items, now, тихие = new Set(), скрытые = new Set()) {
  const burning = [], later = [], undated = [], отложенные = [];
  // Просроченные больше не просто считаются, а собираются списком.
  //
  // Раньше они молча выпадали: past++ и всё. Для Classroom это было
  // терпимо — там в прошлом лежат позапрошлогодние сданные задания.
  // Но Canvas и Edpuzzle отдают только НЕСДАННОЕ, значит просроченное
  // там означает «не сдал и опоздал». О таком надо кричать, а не молчать.
  //
  // пользователь посмотрел на пример и попросил показывать — но под «Горит»,
  // а не над ним: горящее важнее того, что уже провалено.
  const просрочено = [];
  const пропавшие = [];   // удалённые учителем
  let past = 0;
  const завтра = new Date(now.getTime() + 864e5);

  for (const x of items) {
    // Удалённое учителем — в свою корзину и больше никуда. Оно не горит,
    // не просрочено и не «впереди»: работы больше нет, есть только след
    // о том, что она была.
    if (x.удалено) { пропавшие.push(x); continue; }

    // СДАННОЕ НЕ ПОКАЗЫВАЕМ ВОВСЕ.
    //
    // Сдав задание, Classroom меняет первую строку на «Completed Assignment»
    // или «Completed Question». Проверка ниже (/assignment|quiz/) на такую
    // строку отвечает «да», поэтому сданное продолжало гореть наравне
    // с несданным. На живых данных 24 августа таких было пять: четыре
    // «Completed Assignment» и одно «Completed Question».
    //
    // Из памяти их не выбрасываем — они и дальше приходят из Classroom,
    // просто не попадают ни в одну корзину. Иначе правило «три промаха
    // подряд» решило бы, что задания исчезли, и они мигнули бы «новыми»,
    // если учитель вернёт работу на доработку.
    if (/^completed\b/i.test(x.type || '')) continue;

    // Classroom сам подписывает тип первой строкой: Assignment,
    // Quiz assignment или Material. Материал — это то, что читают,
    // задание — то, что сдают, и их судьба в сводке разная.
    const задание = /assignment|quiz/i.test(x.type);

    let due = deadline(x, now);
    let note = null;

    const заглушка = x.due_iso
      ? (new Date(x.due_iso) - now > 365 * 864e5)
      : parseDue(x.due, now).placeholder;
    if (due && заглушка) {
      note = 'заглушка';
    }

    if (!due) {
      // Материал без даты — просто материал, показать один раз и забыть.
      if (!задание) { undated.push(x); continue; }

      // пользователь нажал «не срочно» на странице — значит он это задание
      // видел и разобрался. Больше не паникуем, но и не выбрасываем:
      // пусть лежит отдельным списком.
      // Помечаем прямо здесь: странице надо отличить «снятое вручную»
      // от прочего, а по названию раздела этого делать нельзя — оно
      // переводится, и логика развалилась бы при смене языка.
      if (тихие.has(x.id)) { отложенные.push({ ...x, тихое: true }); continue; }

      // А вот задание без даты терять нельзя: сдавать всё равно надо,
      // просто учитель не проставил срок. Долбим как «до завтра».
      due = завтра;
      note = 'безСрока';
    }

    if (due < now) {
      past++;
      просрочено.push({ ...x, due_at: due, note, скрыто: скрытые.has(x.id) });
      continue;
    }
    (due - now <= 7 * 864e5 ? burning : later).push({ ...x, due_at: due, note });
  }

  burning.sort((a, b) => a.due_at - b.due_at);
  later.sort((a, b) => a.due_at - b.due_at);
  // Свежепросроченное сверху: чем недавнее прошляпил, тем важнее.
  просрочено.sort((a, b) => b.due_at - a.due_at);

  // Свежеудалённое сверху: если учитель что-то убрал сегодня, это
  // интереснее, чем убранное месяц назад.
  пропавшие.sort((a, b) => String(b.когдаУдалено || '').localeCompare(String(a.когдаУдалено || '')));

  return { burning, later, undated, отложенные, просрочено, пропавшие, past };
}

/** Задания, которые пользователь убрал из списка просроченных. */
function прочитатьСкрытые() {
  if (!fs.existsSync(HIDDEN_FILE)) return new Set();
  return new Set(
    fs.readFileSync(HIDDEN_FILE, 'utf8').split('\n').map(s => s.trim()).filter(Boolean)
      // Приложение получает id из адреса, где русские буквы приезжают
      // закодированными. Реальные id из латиницы и цифр, но раскодируем
      // на всякий случай — чтобы совпадение не зависело от этого.
      .map(s => { try { return decodeURIComponent(s); } catch { return s; } })
  );
}

/** Читает список заданий, для которых пользователь снял срочность. */
function прочитатьТихие() {
  if (!fs.existsSync(QUIET_FILE)) return new Set();
  return new Set(
    fs.readFileSync(QUIET_FILE, 'utf8').split('\n').map(s => s.trim()).filter(Boolean)
      // Раскодируем так же, как в прочитатьСкрытые: id приезжает из адреса
      // napominalka://, и всё, что не латиница с цифрами, приходит в виде
      // %D0%BF... Настоящих id это не касается, но пусть оба списка ведут
      // себя одинаково — иначе однажды разойдутся именно там, где не ждёшь.
      .map(s => { try { return decodeURIComponent(s); } catch { return s; } })
  );
}

