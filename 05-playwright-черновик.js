/**
 * Быстро оценивает, насколько бодрый сейчас интернет, и возвращает
 * множитель для всех сроков ожидания.
 *
 * Зачем: пороги подобраны на хорошей связи (8 секунд пустому классу,
 * 60 обычному). На плохом интернете восьми секунд не хватит и на
 * настоящий класс — скрипт решит, что заданий нет, хотя они есть.
 * Идея пользователя.
 *
 * Замер намеренно грубый: точность тут не нужна, нужен порядок величины.
 * Тянем маленький файл с того же Google и смотрим, сколько это заняло.
 */
async function замерСети(page) {
  try {
    const мс = await page.evaluate(async () => {
      const t = performance.now();
      await fetch('https://classroom.google.com/favicon.ico',
                  { cache: 'no-store', mode: 'no-cors' });
      return Math.round(performance.now() - t);
    });

    // Пороги на глаз. Первый подняли до 800мс после замера на живой
    // связи: 518мс — это нормальный домашний интернет, а не медленный,
    // и удваивать сроки из-за него незачем.
    const множитель = мс < 800 ? 1 : (мс < 2000 ? 2 : 4);
    console.log(`Связь: ${мс}мс — сроки ожидания ×${множитель}`);
    return множитель;
  } catch (e) {
    // Не смогли даже замерить — считаем, что связь плохая.
    console.warn('Замер связи не удался, беру запас ×4:', e.message);
    return 4;
  }
}

// ── Замок от одновременных запусков ──────────────────────────

/**
 * Пытается занять замок. Возвращает false, если сбор уже идёт.
 *
 * В файле лежит номер процесса. Проверяем не «есть ли файл», а
 * «жив ли тот процесс»: если предыдущий сбор упал или его прибили,
 * файл останется висеть, и без этой проверки скрипт заблокировал бы
 * сам себя навсегда.
 */
function захватитьЗамок() {
  if (fs.existsSync(LOCK_FILE)) {
    const pid = parseInt(fs.readFileSync(LOCK_FILE, 'utf8'), 10);
    let жив = false;
    try {
      // Сигнал 0 ничего не делает, только проверяет, есть ли процесс.
      process.kill(pid, 0);
      жив = true;
    } catch { /* процесса нет — значит замок заброшенный */ }

    if (жив) return false;
    console.log(`Замок остался от упавшего запуска (pid ${pid}), снимаю`);
  }
  fs.writeFileSync(LOCK_FILE, String(process.pid));
  return true;
}

function снятьЗамок() {
  try { fs.unlinkSync(LOCK_FILE); } catch {}
}

