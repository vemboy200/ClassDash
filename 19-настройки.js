/**
 * Настройки в одном месте.
 *
 * ── Зачем ──
 *
 * До этого школьная почта, адрес Canvas и сроки ожидания были вписаны прямо
 * в код, в четырёх разных файлах. Пока система жила на одном ноутбуке, это
 * никому не мешало. Но выложить такое нельзя: чужой человек скачает проект
 * и получит почту пользователя и id его классов, а чтобы запустить у себя —
 * полезет править исходники.
 *
 * Теперь всё личное лежит в `настройки.json`, а рядом `настройки.пример.json`
 * с пустыми полями — его и видно в репозитории.
 *
 * ── Как менять ──
 *
 *   через шестерёнку на странице-сводке (самое простое)
 *   node 19-настройки.js --задать почта kto@to.net
 *   node 19-настройки.js --показать
 *   руками в настройки.json
 *
 * ── Почему файла может не быть ──
 *
 * И это НОРМАЛЬНО. Нет файла — берутся значения по умолчанию, система
 * работает. Настройки не должны быть тем, без чего ничего не заводится:
 * человек, который только скачал проект, должен увидеть его живым,
 * а не список ошибок.
 */

const fs = require('fs');
const path = require('path');

const ФАЙЛ = path.join(__dirname, 'настройки.json');
const ПРИМЕР = path.join(__dirname, 'настройки.пример.json');

/**
 * Значения по умолчанию. Они же — список того, что вообще можно настроить:
 * ключа нет в этом списке, значит его нельзя задать и снаружи.
 *
 * Проверка `можно` не для красоты. Значения приезжают со страницы через
 * ссылку napominalka://, то есть снаружи. Без белого списка ключей туда
 * можно было бы записать что угодно и под любым именем.
 */
const ПО_УМОЛЧАНИЮ = {
  // Школьная почта. Подставляется в ссылки как ?authuser=
  // Без неё Google открывает класс под личным аккаунтом и говорит
  // «Class not found» — проверено вживую.
  почта: '',

  // Номер аккаунта в мультивходе Google внутри профиля Playwright.
  // Профиль отдельный и аккаунт в нём один, поэтому 0.
  аккаунт: 0,

  // Адрес школьного Canvas. Пустой — Canvas не читается вовсе.
  canvas: '',

  // Язык интерфейса: ru или en.
  язык: 'ru',

  // Часы полной сводки: в них напоминаем обо всём горящем.
  часыСводки: [8, 18],

  // Классы, которые читать не надо. По имени, как в Classroom.
  исключения: [],

  // Сроки ожидания, миллисекунды.
  ожиданиеКласса: 60000,   // обычный класс
  ожиданиеПустого: 8000,   // класс, где заданий не было никогда
  пределПрохода: 300000,   // дольше — считаем зависшим и обрываем

  // Порт домашнего API.
  портAPI: 8734,
};

const ТИПЫ = {
  почта: 'строка', canvas: 'строка', язык: 'язык',
  аккаунт: 'число', ожиданиеКласса: 'число', ожиданиеПустого: 'число',
  пределПрохода: 'число', портAPI: 'число',
  часыСводки: 'числа', исключения: 'строки',
};

function прочитать() {
  const итог = { ...ПО_УМОЛЧАНИЮ };
  if (!fs.existsSync(ФАЙЛ)) return итог;
  try {
    const свои = JSON.parse(fs.readFileSync(ФАЙЛ, 'utf8'));
    for (const ключ of Object.keys(ПО_УМОЛЧАНИЮ)) {
      if (свои[ключ] !== undefined && свои[ключ] !== null) итог[ключ] = свои[ключ];
    }
  } catch (e) {
    // Битый файл не должен останавливать сбор: скажем и поедем дальше
    // на значениях по умолчанию. Молчать тут нельзя — человек будет
    // гадать, почему его правка не подействовала.
    console.warn(`настройки.json не разобрался (${e.message}) — беру значения по умолчанию`);
  }
  return итог;
}

/**
 * Проверяет и приводит значение к нужному виду.
 * Возвращает {ок, значение} либо {ок: false, почему}.
 */
function проверить(ключ, сырое) {
  if (!(ключ in ПО_УМОЛЧАНИЮ)) return { ок: false, почему: `нет такой настройки: ${ключ}` };
  const вид = ТИПЫ[ключ];

  if (вид === 'число') {
    const n = Number(сырое);
    if (!Number.isFinite(n) || n < 0) return { ок: false, почему: 'нужно число' };
    return { ок: true, значение: n };
  }
  if (вид === 'язык') {
    const я = String(сырое).trim().toLowerCase();
    if (я !== 'ru' && я !== 'en') return { ок: false, почему: 'язык бывает ru или en' };
    return { ок: true, значение: я };
  }
  if (вид === 'числа') {
    // Этим видом описаны только «часы полной сводки», поэтому и проверка
    // часовая: целое от 0 до 23.
    //
    // Раньше здесь стояло просто Number.isFinite, и пустое поле давало
    // НЕ пустой список, а [0]: "".split(/[,\s]+/) возвращает [""],
    // а Number("") — это ноль. То есть человек стирал поле, чтобы выключить
    // напоминания, а получал сводку в полночь — когда launchd всё равно
    // не запускается. Тишина без объяснений.
    //
    // Пустые куски выбрасываем ДО Number(): именно из-за них пустое поле
    // и превращалось в ноль. Заодно ловим опечатки: «25» и «утром» раньше
    // принимались молча.
    const части = (Array.isArray(сырое) ? сырое : String(сырое).split(/[,\s]+/))
      .map(ч => String(ч).trim()).filter(ч => ч !== '');
    const числа = части.map(Number)
      .filter(n => Number.isInteger(n) && n >= 0 && n <= 23);
    if (части.length && !числа.length) return { ок: false, почему: 'часы бывают от 0 до 23' };
    return { ок: true, значение: числа };
  }
  if (вид === 'строки') {
    const части = Array.isArray(сырое) ? сырое : String(сырое).split(/\s*[,;]\s*/);
    return { ок: true, значение: части.map(s => String(s).trim()).filter(Boolean) };
  }
  return { ок: true, значение: String(сырое).trim() };
}

function записать(ключ, сырое) {
  const п = проверить(ключ, сырое);
  if (!п.ок) return п;

  const текущие = прочитать();
  текущие[ключ] = п.значение;
  fs.writeFileSync(ФАЙЛ, JSON.stringify(текущие, null, 2));
  return { ок: true, значение: п.значение };
}

/** Пример для репозитория: те же ключи, но без ничего личного. */
function записатьПример() {
  const пример = { ...ПО_УМОЛЧАНИЮ };
  пример.почта = 'твоя.школьная@почта.example';
  пример.canvas = 'https://твоя-школа.instructure.com';
  fs.writeFileSync(ПРИМЕР, JSON.stringify(пример, null, 2));
  return ПРИМЕР;
}

/**
 * Применяет пачку настроек, пришедшую со страницы-сводки.
 *
 * ── Почему пачкой и почему в base64 ──
 *
 * Страница не может писать на диск, поэтому зовёт Напоминалку ссылкой
 * napominalka:// — тем же способом, что «не срочно» и «скрыть». Но там
 * передавался один короткий id, а тут летят почта, адрес школы и список
 * исключений: слэши, двоеточия, запятые, собака. В адресе всё это значит
 * что-то своё и разъезжается.
 *
 * base64 превращает пачку в набор безобидных букв — один кусок, без разбора
 * на части. Это не шифрование и не прячет ничего: любой может раскодировать.
 * Задача только в том, чтобы адрес доехал целым.
 *
 * ── Что здесь проверяется ──
 *
 * ВСЁ. Значения приходят снаружи, из адресной строки, поэтому:
 *   - разбирается ли это вообще как JSON;
 *   - есть ли такой ключ в белом списке (чужие молча пропускаются);
 *   - подходит ли значение по виду (число числом, язык из двух известных).
 *
 * Напоминалка передаёт кусок в кавычках (`quoted form of`), так что вклеить
 * туда команду оболочки нельзя. Разбор идёт здесь, где для этого есть
 * настоящий JSON, а не в AppleScript.
 */
function применитьПачку(куском) {
  let разобрано;
  try {
    // base64url -> обычный base64: в адресе «+» и «/» значат своё,
    // поэтому страница шлёт их как «-» и «_».
    const обычный = String(куском).replace(/-/g, '+').replace(/_/g, '/');
    разобрано = JSON.parse(Buffer.from(обычный, 'base64').toString('utf8'));
  } catch (e) {
    return { ок: false, почему: 'не разобрал: ' + e.message };
  }
  if (!разобрано || typeof разобрано !== 'object' || Array.isArray(разобрано)) {
    return { ок: false, почему: 'ожидался набор настроек' };
  }

  const принято = [];
  const отвергнуто = [];
  const текущие = прочитать();

  for (const [ключ, значение] of Object.entries(разобрано)) {
    const п = проверить(ключ, значение);
    if (п.ок) { текущие[ключ] = п.значение; принято.push(ключ); }
    else отвергнуто.push(`${ключ}: ${п.почему}`);
  }

  if (принято.length) fs.writeFileSync(ФАЙЛ, JSON.stringify(текущие, null, 2));
  return { ок: принято.length > 0, принято, отвергнуто };
}

module.exports = { прочитать, записать, проверить, записатьПример, применитьПачку,
                   ПО_УМОЛЧАНИЮ, ТИПЫ, ФАЙЛ };

if (require.main === module) {
  const арг = process.argv.slice(2);

  if (арг[0] === '--задать' && арг[1]) {
    const итог = записать(арг[1], арг.slice(2).join(' '));
    if (итог.ок) console.log(`${арг[1]} = ${JSON.stringify(итог.значение)}`);
    else { console.error(итог.почему); process.exit(1); }

  } else if (арг[0] === '--изурл' && арг[1]) {
    const итог = применитьПачку(арг[1]);
    if (итог.принято && итог.принято.length) console.log('принято: ' + итог.принято.join(', '));
    if (итог.отвергнуто && итог.отвергнуто.length) console.error('отвергнуто: ' + итог.отвергнуто.join('; '));
    if (!итог.ок) { console.error(итог.почему || 'ничего не принято'); process.exit(1); }

  } else if (арг[0] === '--пример') {
    console.log('записан', записатьПример());

  } else {
    console.log(JSON.stringify(прочитать(), null, 2));
  }
}
