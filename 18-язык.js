/**
 * Русские числительные: 1 новое, 2 новых, 5 новых.
 * Английскому это не нужно — там хватает единственного и множественного.
 */
function склонение(n, один, два, много) {
  const п = n % 100;
  if (п >= 11 && п <= 14) return много;
  const е = n % 10;
  return е === 1 ? один : (е >= 2 && е <= 4 ? два : много);
}

function определитьЯзык() {
  const арг = process.argv;
  const i = арг.indexOf('--язык');
  if (i !== -1 && арг[i + 1] && СЛОВАРИ[арг[i + 1]]) return арг[i + 1];

  // Сначала настройки, потом старый язык.txt — он остался ради тех,
  // у кого он уже создан. Новым ничего создавать не надо.
  try {
    const из = require('./19-настройки.js').прочитать().язык;
    if (СЛОВАРИ[из]) return из;
  } catch { /* настроек нет — смотрим дальше */ }

  if (fs.existsSync(ФАЙЛ_ЯЗЫКА)) {
    try {
      const код = fs.readFileSync(ФАЙЛ_ЯЗЫКА, 'utf8').trim().toLowerCase();
      if (СЛОВАРИ[код]) return код;
    } catch { /* не прочитался — русский */ }
  }
  return 'ru';
}

let ЯЗЫК = определитьЯзык();
let СЛОВАРЬ = СЛОВАРИ[ЯЗЫК];

/**
 * Перевод по ключу. Если ключа нет ни в одном словаре — возвращаем сам ключ.
 *
 * ПОЧЕМУ НЕ ПАДАЕМ: забытый ключ должен выглядеть как странная надпись
 * на странице, а не как рухнувший сбор. Пропущенное слово человек заметит
 * и скажет; молчащая система — хуже.
 */
function т(ключ, ...аргументы) {
  const значение = СЛОВАРЬ[ключ] !== undefined ? СЛОВАРЬ[ключ] : СЛОВАРИ.ru[ключ];
  if (значение === undefined) return ключ;
  return typeof значение === 'function' ? значение(...аргументы) : значение;
}

function установитьЯзык(код) {
  if (!СЛОВАРИ[код]) return false;
  ЯЗЫК = код;
  СЛОВАРЬ = СЛОВАРИ[код];
  return true;
}

const текущийЯзык = () => ЯЗЫК;
const локаль = () => т('локаль');

module.exports = { т, установитьЯзык, текущийЯзык, локаль, склонение, СЛОВАРИ };
