/**
 * Транскрипты видео из Edpuzzle.
 *
 * ── Как это работает ──
 *
 *   страница задания → адрес файла .webm → ffmpeg вытаскивает звук
 *   → whisper распознаёт локально → текст ложится в отдельный файл
 *
 * Проверено на живом видео 11 августа: 7,5 минут звука распознались
 * за 13 секунд (Metal, то есть на видеоядре мака).
 *
 * ── Чего здесь НЕТ и не будет ──
 *
 * Плеер не запускается. Видео не проигрывается, вопросы не всплывают,
 * прогресс задания не идёт. ffmpeg тянет файл напрямую по адресу.
 *
 * Это принципиально: транскрипт помогает понять видео, которое пользователь
 * и так обязан посмотреть. Всё, что заменяет просмотр — перемотка
 * в конец, вытаскивание ответов, — за границей, которую мы провели
 * в первый день. Ответы, кстати, лежат в том же ответе API открыто;
 * мы их не берём сознательно, а не потому что не можем.
 *
 * ── Ограничение, которое снимется только в сентябре ──
 *
 * Всё проверено на СДАННОМ задании. Как поведёт себя Edpuzzle с новым,
 * непройденным — неизвестно: возможно, открытие страницы отметит его
 * начатым. Поэтому при первом настоящем задании проверить вручную.
 */

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const os = require('os');

const МОДЕЛЬ = path.join(os.homedir(), '.cache/whisper/ggml-small.en.bin');

/** Есть ли всё нужное, чтобы вообще браться. */
function готовность() {
  const есть = (кто) => {
    try { execFileSync('which', [кто], { stdio: 'pipe' }); return true; }
    catch { return false; }
  };
  if (!есть('ffmpeg')) return 'нет ffmpeg (brew install ffmpeg)';
  if (!есть('whisper-cli')) return 'нет whisper (brew install whisper-cpp)';
  if (!fs.existsSync(МОДЕЛЬ)) return `нет модели: ${МОДЕЛЬ}`;
  return null;
}

/**
 * Достаёт адрес видеофайла со страницы задания.
 *
 * Адрес подписан и живёт несколько часов, поэтому запоминать его
 * бессмысленно — берём заново каждый раз, когда нужен.
 *
 * ВАЖНО про адрес: нужен именно вид с attachmentId и summary.
 * Без них Edpuzzle показывает итоговую сводку без плеера — это
 * пользователь нашёл руками, ткнув в интерфейс, после того как я семью
 * пробами перебирал адреса вслепую.
 */
async function добытьАдресВидео(page, assignmentId, attachmentId) {
  const url = `https://edpuzzle.com/assignments/${assignmentId}/watch`
            + (attachmentId ? `?attachmentId=${attachmentId}&summary=` : '');
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.waitForTimeout(9000);

  return await page.evaluate(() => {
    const v = document.querySelector('video');
    return v ? (v.currentSrc || v.src || null) : null;
  });
}

/**
 * Звук -> текст. Возвращает {текст, поВремени}.
 *
 * whisper выдаёт два вида сразу: сплошной текст для чтения и разметку
 * с отметками времени. Второе нужно, чтобы перемотать видео к
 * непонятному месту вместо того, чтобы искать его наугад.
 */
function распознать(адресВидео, кудаПапка, имя) {
  fs.mkdirSync(кудаПапка, { recursive: true });
  const wav = path.join(кудаПапка, `${имя}.wav`);
  const основа = path.join(кудаПапка, имя);

  // Скачивание и извлечение звука одной командой: видео на диск
  // не ложится вообще, ffmpeg читает его из сети и сразу выбрасывает
  // картинку. Сорокамегабайтный ролик превращается в несколько
  // мегабайт звука.
  execFileSync('ffmpeg', [
    '-y', '-loglevel', 'error',
    '-i', адресВидео,
    '-vn',            // без картинки
    '-ac', '1',       // одна дорожка
    '-ar', '16000',   // 16 кГц — то, что ждёт whisper
    wav,
  ], { timeout: 10 * 60 * 1000 });

  execFileSync('whisper-cli', [
    '-m', МОДЕЛЬ,
    '-f', wav,
    '-otxt', '-ovtt',   // сплошной текст и разметка по времени
    '-of', основа,
  ], { timeout: 30 * 60 * 1000 });

  const текст = fs.existsSync(основа + '.txt')
    ? fs.readFileSync(основа + '.txt', 'utf8').trim() : '';
  const поВремени = fs.existsSync(основа + '.vtt')
    ? fs.readFileSync(основа + '.vtt', 'utf8').trim() : '';

  // Звук больше не нужен, а весит он прилично.
  try { fs.unlinkSync(wav); } catch {}

  return { текст, поВремени };
}

module.exports = { готовность, добытьАдресВидео, распознать, МОДЕЛЬ };
